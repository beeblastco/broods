#!/usr/bin/env bash
# Writes a Claude Code cloud environment's setup script and env file to
# ~/.broods-cloud/ (0600, outside the repo). Root AGENTS.md, Cloud Sessions,
# says how they are used and why there are no network secrets.
#
#   --login  sign the probe user in to dev (open the printed URL in
#            a private window). Logins live in ~/.broods-cloud/test-account and
#            last 90 days. Only the probe's login is ever written to env.txt.
#
# Values: broods tokens from that login only; E2E_EMAIL / E2E_PASSWORD from the
# shell, else apps/dashboard/.env.local; ANTHROPIC_API_KEY and OPENAI_API_KEY
# from the shell. Versions come from the checkout: rerun after a bump.
#
# Usage: bash scripts/cloud-setup.sh [--login]
set -euo pipefail

repo=$(git -C "$(dirname "$0")" rev-parse --show-toplevel)
out="${BROODS_CLOUD_DIR:-$HOME/.broods-cloud}"
# Absolute, so --login's HOME and from_login's read name the same config file.
mkdir -p "$out"
out=$(cd "$out" && pwd)
test_home="$out/test-account"
dev_gateway=gateway.dev.broods.app
login=false
for arg in "$@"; do
  case "$arg" in
    --login) login=true ;;
    *) echo "cloud-setup: unknown option $arg" >&2; exit 1 ;;
  esac
done
mkdir -p "$test_home"
chmod 700 "$out" "$test_home"

if $login; then
  broods_bin=$(command -v broods || true)
  [ -n "$broods_bin" ] || { echo "cloud-setup: install the CLI first (bun add -g broods)" >&2; exit 1; }
  # No browser launch: your normal browser is signed in as you, not the test user.
  shim=$(mktemp -d)
  printf '#!/bin/sh\nexit 0\n' >"$shim/xdg-open"
  cp "$shim/xdg-open" "$shim/open"
  chmod +x "$shim/xdg-open" "$shim/open"
  echo "Open the URL below in a private window and sign in as the probe user."
  # From $test_home: login writes .env.local defaults into the current dir.
  (cd "$test_home" && HOME="$test_home" PATH="$shim:$PATH" "$broods_bin" login --dashboard-url https://dashboard.dev.broods.app)
  rm -rf "$shim"
fi

bun_version=$(tr -d '[:space:]' <"$repo/.bun-version") || true
playwright_version=$(grep -o '"playwright@[0-9.]*"' "$repo/bun.lock" | head -1 | tr -d '"' | cut -d@ -f2) || true
lean_toolchain=$(tr -d '[:space:]' <"$repo/verification/lean-toolchain") || true
convex_image=$(grep -o 'ghcr.io/convex/convex-backend@sha256:[0-9a-f]*' "$repo/scripts/local-stack.ts" | head -1) || true
traefik_image=$(grep -o 'TRAEFIK_IMAGE = "[^"]*"' "$repo/scripts/local-stack.ts" | cut -d'"' -f2) || true
for name in bun_version playwright_version lean_toolchain convex_image traefik_image; do
  [ -n "${!name}" ] || { echo "cloud-setup: could not read $name from the checkout" >&2; exit 1; }
done

# Each key from the checkout's dashboard .env.local, else the main checkout's
# (a linked worktree usually has none, or one without the probe login).
main_checkout=$(dirname "$(git -C "$repo" rev-parse --path-format=absolute --git-common-dir)")
from_dotenv() {
  local file value
  for file in "$repo/apps/dashboard/.env.local" "$main_checkout/apps/dashboard/.env.local"; do
    [ -f "$file" ] || continue
    value=$(grep -m1 "^$1=" "$file" | cut -d= -f2- | sed -E 's/^"(.*)"$/\1/' || true)
    [ -n "$value" ] && { printf %s "$value"; return 0; }
  done
}
# The probe's login only: a person's own token must never reach a cloud session.
from_login() {
  [ -f "$test_home/.broods/config.json" ] || return 0
  CONFIG="$test_home/.broods/config.json" SERVER="https://$1" PROBE="$probe_email" bun -e '
    const login = JSON.parse(await Bun.file(process.env.CONFIG).text()).logins?.[process.env.SERVER];
    if (login && login.user?.email !== process.env.PROBE) {
      console.error(`cloud-setup: ${process.env.SERVER} login is ${login.user?.email}, not the probe ${process.env.PROBE}; rerun with --login`);
      process.exit(1);
    } else process.stdout.write(login?.token ?? "");'
}
pick() { local v="${!1:-}"; [ -n "$v" ] && printf %s "$v" || printf %s "$2"; }

# The one probe user (apps/dashboard/AGENTS.md); nothing else may ship.
probe_email=cloud-agent@beeblast.co
e2e_email=$(pick E2E_EMAIL "$(from_dotenv E2E_EMAIL)")
if [ "$e2e_email" != "$probe_email" ]; then
  echo "cloud-setup: E2E_EMAIL is ${e2e_email:-unset}, not the probe $probe_email" >&2
  exit 1
fi
e2e_password=$(pick E2E_PASSWORD "$(from_dotenv E2E_PASSWORD)")
dev_token=$(from_login "$dev_gateway")
anthropic_key="${ANTHROPIC_API_KEY:-}"
openai_key="${OPENAI_API_KEY:-}"

umask 077

cat >"$out/setup.sh" <<EOF
#!/bin/bash
# Generated by scripts/cloud-setup.sh. Runs as root before Claude Code starts;
# cached ~7 days when it ends in ~5 min. Per-session work (dockerd, bun install)
# is scripts/cloud-session-start.sh, wired in .claude/settings.json.
set -uo pipefail
export DEBIAN_FRONTEND=noninteractive

# A failed install is recorded, not fatal: a non-zero exit would stop every
# session from starting. The session hook reports the record to the agent,
# which can install the missing piece.
failed=/var/lib/broods-cloud-setup-failed
rm -f "\$failed"
job() { local name=\$1; shift; "\$@" || echo "\$name (see /tmp/setup-\$name.log)" >>"\$failed"; }

job bun npm install -g "bun@${bun_version}" >/tmp/setup-bun.log 2>&1

if ! docker info >/dev/null 2>&1; then
  (dockerd >/tmp/dockerd.log 2>&1 &)
  for _ in \$(seq 1 30); do docker info >/dev/null 2>&1 && break; sleep 1; done
fi
job convex timeout 240 docker pull "${convex_image}" >/tmp/setup-convex.log 2>&1 &
job traefik timeout 240 docker pull "${traefik_image}" >/tmp/setup-traefik.log 2>&1 &
job playwright timeout 240 npx -y "playwright@${playwright_version}" install --with-deps chromium >/tmp/setup-playwright.log 2>&1 &
job lean timeout 240 bash -c 'curl -sSf https://raw.githubusercontent.com/leanprover/elan/master/elan-init.sh |
  sh -s -- -y --default-toolchain "${lean_toolchain}" && "\$HOME"/.elan/bin/elan toolchain install "${lean_toolchain}" &&
  ln -sf "\$HOME"/.elan/bin/* /usr/local/bin/' >/tmp/setup-lean.log 2>&1 &
# User-scope plugins never reach a cloud session, so install them here.
job plugins bash -c 'timeout 240 claude plugin marketplace add anthropics/claude-plugins-official &&
  for p in code-simplifier commit-commands frontend-design; do
    timeout 60 claude plugin install "\$p@claude-plugins-official" --scope user || exit 1
  done' >/tmp/setup-plugins.log 2>&1 &

wait
[ -s "\$failed" ] && { echo "cloud setup: some installs failed:"; cat "\$failed"; }
# Stop dockerd so the cached snapshot holds a clean /var/lib/docker.
pkill dockerd 2>/dev/null && for _ in \$(seq 1 20); do pgrep dockerd >/dev/null || break; sleep 1; done
exit 0
EOF

cat >"$out/env.txt" <<EOF
BROODS_DEV_TOKEN=${dev_token}
E2E_EMAIL=${e2e_email}
E2E_PASSWORD=${e2e_password}
CLOUD_ANTHROPIC_API_KEY=${anthropic_key}
OPENAI_API_KEY=${openai_key}
CLAUDE_CODE_EXPERIMENTAL_AGENT_TEAMS=1
EOF

chmod 600 "$out/setup.sh" "$out/env.txt"

echo "Wrote $out/{setup.sh,env.txt}"
missing=()
for pair in "BROODS_DEV_TOKEN:$dev_token" "E2E_EMAIL:$e2e_email" \
  "E2E_PASSWORD:$e2e_password" "ANTHROPIC_API_KEY:$anthropic_key" "OPENAI_API_KEY:$openai_key"; do
  [ -n "${pair#*:}" ] || missing+=("${pair%%:*}")
done
[ ${#missing[@]} -eq 0 ] || echo "Empty: ${missing[*]}. Tokens come from --login, the rest from the shell; rerun after."
[ -n "$dev_token" ] || echo "No test-account login yet: run bash scripts/cloud-setup.sh --login"
